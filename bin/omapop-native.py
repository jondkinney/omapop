#!/usr/bin/python3 -I
"""Explicit, bounded Linux handoffs for reviewed ports. JSON on stdin.

Print and execute are confirmed by Service.qml before this helper is started.
This is not an IPC service. It cannot download/install software or accept an
executable path. Commands use fixed argument arrays and selected text is data.
"""
import ipaddress
import json
import os
from pathlib import Path
import re
import signal
import socket
import stat
import subprocess
import sys
import tempfile
from urllib.parse import urlsplit

MAX_BYTES = 131072
BROWSERS = {'firefox': '/usr/bin/firefox', 'chromium': '/usr/bin/chromium',
            'brave': '/usr/bin/brave', 'chrome': '/usr/bin/google-chrome-stable'}


def run(argv, data=None, timeout=10):
    if not os.path.isfile(argv[0]) or not os.access(argv[0], os.X_OK):
        raise ValueError('Required application is missing: ' + Path(argv[0]).name)
    env = dict(os.environ)
    for name in ('BASH_ENV', 'ENV', 'PYTHONPATH', 'PYTHONHOME', 'LD_PRELOAD', 'LD_LIBRARY_PATH'):
        env.pop(name, None)
    env['PATH'] = '/usr/bin:/bin'
    # Output is discarded: native tools can print arbitrary server/app messages.
    result = subprocess.run(['/usr/bin/setpriv', '--pdeathsig', 'TERM', '--', *argv], input=data, stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, timeout=timeout, env=env)
    if result.returncode:
        raise ValueError(Path(argv[0]).name + ' could not complete the action')


def launch(argv):
    if not os.path.isfile(argv[0]) or not os.access(argv[0], os.X_OK):
        raise ValueError('Required application is missing: ' + Path(argv[0]).name)
    # GUI applications may own the process for their entire lifetime. Detached
    # stdio makes launching bounded; this does not claim the app accepted input.
    env = {k: v for k, v in os.environ.items() if k not in ('BASH_ENV', 'ENV', 'LD_PRELOAD', 'LD_LIBRARY_PATH')}
    env['PATH'] = '/usr/bin:/bin'
    subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, start_new_session=True, close_fds=True, env=env)


def https(value):
    if not isinstance(value, str) or len(value) > 8192 or re.search(r'[\x00-\x20\x7f\\]', value):
        raise ValueError('Use one HTTPS URL without whitespace')
    url = urlsplit(value)
    if url.scheme != 'https' or not url.hostname or url.username is not None or url.password is not None:
        raise ValueError('Use one HTTPS URL without embedded credentials')
    return value


def capture(text, category, base=None):
    # Walk using directory descriptors so symlinks cannot redirect private files.
    root = Path(base) if base else Path.home() / '.local/share/omapop/captures'
    if not root.is_absolute(): raise ValueError('Capture directory must be absolute')
    fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY)
    try:
        for part in root.parts[1:]:
            try: os.mkdir(part, mode=0o700, dir_fd=fd)
            except FileExistsError: pass
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd); fd = child
        info = os.fstat(fd)
        if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o077:
            raise ValueError('Capture directory must be private (mode 0700)')
        entries = []
        with os.scandir(fd) as scan:
            for entry in scan:
                entries.append(entry.name)
                if len(entries) >= 200: break
        if len(entries) >= 200: raise ValueError('Capture folder has 200 files; move old captures before adding more')
        size = sum(os.stat(name, dir_fd=fd, follow_symlinks=False).st_size for name in entries)
        if size + len(text.encode()) > 10 * 1024 * 1024: raise ValueError('Capture folder exceeds 10 MiB')
        # Name generated by the host, never by selected text or extension options.
        name = category + '-' + os.urandom(12).hex() + ('.sh' if category == 'script' else '.txt')
        file = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=fd)
        with os.fdopen(file, 'w', encoding='utf-8') as stream: stream.write(text)
        return str(root / name)
    finally: os.close(fd)


def dispatch(request):
    if not isinstance(request, dict): raise ValueError('Expected a JSON object')
    action, text, opts = request.get('action'), request.get('text'), request.get('options', {})
    if not isinstance(text, str) or not text or len(text.encode()) > MAX_BYTES or '\0' in text:
        raise ValueError('Select nonempty text of at most 128 KiB, without NUL')
    if not isinstance(opts, dict): raise ValueError('Invalid action options')
    if action == 'dns':
        value = text.strip()
        host = urlsplit(value).hostname if '://' in value else value
        if not host or len(host) > 253 or not re.fullmatch(r'[a-zA-Z0-9.:-]+', host):
            raise ValueError('Select a hostname, IP address or web URL')
        try: host = str(ipaddress.ip_address(host))
        except ValueError:
            if not all(re.fullmatch(r'[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?', s) for s in host.rstrip('.').split('.')):
                raise ValueError('Invalid hostname')
        addresses = sorted({r[4][0] for r in socket.getaddrinfo(host, None, type=socket.SOCK_STREAM)})
        if not addresses or len(addresses) > 32: raise ValueError('No bounded DNS result')
        return {'text': '\n'.join(addresses)}
    if action == 'zeal':
        if len(text) > 1000: raise ValueError('Documentation query exceeds 1,000 characters')
        launch(['/usr/bin/zeal', '--', text.strip()]); return {'message': 'Opened Zeal'}
    if action == 'browser':
        browser = opts.get('browser', 'default')
        executable = '/usr/bin/xdg-open' if browser == 'default' else BROWSERS.get(browser)
        if not executable: raise ValueError('Unknown browser choice')
        launch([executable, https(text.strip())]); return {'message': 'Opened browser'}
    if action == 'speech':
        if len(text) > 1000: raise ValueError('Speech is limited to 1,000 characters')
        # espeak-ng accepts stdin as text; no SSML option, shell or option parsing
        # of the selection. It stays attached so the 115-second limit is effective.
        run(['/usr/bin/espeak-ng', '--stdin'], text.encode(), timeout=115); return {'message': 'Speech finished'}
    if action == 'print':
        printer = opts.get('printer', '')
        if not isinstance(printer, str) or (printer and not re.fullmatch(r'[A-Za-z0-9][\w.-]{0,63}', printer)):
            raise ValueError('Invalid printer name')
        argv = ['/usr/bin/lp', '-t', 'Omapop selection'] + (['-d', printer] if printer else [])
        run(argv, text.encode()); return {'message': 'Submitted to printer'}
    if action in ('note', 'editor'):
        path = capture(text, 'note' if action == 'note' else 'edit')
        if action == 'editor': launch(['/usr/bin/xdg-open', path])
        return {'text': path, 'message': 'Saved ' + path}
    if action == 'terminal':
        launch(['/usr/bin/xdg-terminal-exec']); return {'message': 'Command copied; paste it into the terminal'}
    if action == 'execute':
        if not os.path.isfile('/usr/bin/xdg-terminal-exec'): raise ValueError('xdg-terminal-exec is required')
        path = capture(text, 'script')
        # Fixed launcher body; the selection is a separately stored script. No
        # interpolation into bash -c. Confirmation is mandatory in the QML host.
        launcher = '/usr/bin/bash --noprofile --norc "$1"; printf "\\nPress Enter to close..."; IFS= read -r omapop_reply'
        launch(['/usr/bin/xdg-terminal-exec', '/usr/bin/bash', '--noprofile', '--norc', '-c', launcher, 'omapop', path])
        return {'message': 'Opened the confirmed script in a terminal'}
    raise ValueError('Unknown native action')


def main():
    signal.signal(signal.SIGALRM, lambda *_: (_ for _ in ()).throw(TimeoutError('Native action timed out')))
    signal.alarm(12)
    try:
        raw = sys.stdin.buffer.read(262145)
        if len(raw) > 262144: raise ValueError('Request exceeds 256 KiB')
        request = json.loads(raw)
        if isinstance(request, dict) and request.get('action') == 'speech': signal.alarm(118)
        result = dispatch(request)
        print(json.dumps(dict(ok=True, **result)))
    except (ValueError, OSError, TimeoutError, subprocess.TimeoutExpired) as error:
        # DNS/native exceptions may include selected text; use fixed errors for
        # external failures and only our own ValueError messages for validation.
        message = str(error) if type(error) is ValueError else 'Native action failed, timed out, or needs its Linux application installed'
        print(json.dumps({'ok': False, 'error': message[:200]}))
    finally: signal.alarm(0)


if __name__ == '__main__': main()
